import AxeBuilder from '@axe-core/playwright';
import { expect, test } from '@playwright/test';
import { reviewWorkspace } from './fixtures/ux-review';

test('入职默认直接确认，补录可精确到秒且未来时间给出明确提示',async({page},testInfo)=>{
  await reviewWorkspace(page);
  await page.emulateMedia({reducedMotion:'reduce'});
  const application = { id: 'app-ledger', candidateId: 'person-a', demandId: 'demand-a', jdId: 'jd-a', jdVersionId: 'jd-v2', resumeVersionId: 'resume-a', workflowTemplateVersionId: 'workflow', matchPlanVersionId: 'plan', recruitmentType: 'INTERNAL', currentStage: 'OFFER', onboardingStatus: 'IN_PROGRESS', onboardingStartedAt: '2026-09-07T01:00:00Z', ownerUserId: 'hr-a', ownerDepartmentId: 'dept-a', outcome: null, terminalAt: null, version: 1, createTime: '2026-09-07T01:00:00Z', updateTime: '2026-09-07T01:00:00Z' };
  const detail={application,collaboratorUserIds:[],workflowSteps:[],decisions:[],offerStatusRecords:[{status:'ISSUED',occurredAt:'2026-09-07T01:00:00Z'}],elapsedSeconds:0};
  const writes:Record<string,unknown>[]=[];
  await page.route('**/api/v1/applications?**',route=>route.fulfill({json:{items:[application],hasMore:false,nextCursor:null}}));
  await page.route('**/api/v1/applications/app-ledger',route=>route.fulfill({json:detail}));
  await page.route('**/api/v1/applications/app-ledger/onboarding-reviews',route=>{writes.push(route.request().postDataJSON());return route.fulfill({json:{id:'onboard'}});});
  await page.goto('/onboarded');
  await page.getByRole('button',{name:'确认实际入职',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'确认实际入职',exact:true});
  await expect(dialog.getByRole('radio',{name:'现在入职'})).toBeChecked();
  await expect(dialog.getByLabel('实际入职日期与时间（北京时间）')).toHaveCount(0);
  expect((await new AxeBuilder({page}).include('[role="dialog"]').withTags(['wcag2a','wcag2aa']).analyze()).violations).toEqual([]);
  await dialog.getByRole('button',{name:'确认已入职'}).hover();
  await page.screenshot({path:testInfo.outputPath('onboarding-now.png'),fullPage:true,animations:'disabled'});
  await dialog.getByRole('radio',{name:'补录入职时间'}).click();
  const input=dialog.getByLabel('实际入职日期与时间（北京时间）');
  await expect(input).toHaveAttribute('step','1');
  await input.fill('2099-01-01T09:31:24');
  await dialog.getByRole('button',{name:'确认已入职'}).click();
  await expect(dialog.getByText('实际入职不能选择未来时间')).toBeVisible();
  expect(writes).toEqual([]);
  await dialog.getByRole('radio',{name:'现在入职'}).click();
  await dialog.getByRole('button',{name:'确认已入职'}).click();
  await expect(dialog).toHaveCount(0);
  expect(writes).toEqual([{onboardedAt:'2026-09-07T01:30:00.000Z'}]);
});
